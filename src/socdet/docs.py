"""Generate docs/rules.md (every rule with its Splunk and Sentinel query) and docs/coverage.md."""

from __future__ import annotations

from .attack import TACTICS, TECHNIQUES, coverage, technique_url
from .backends import to_sentinel, to_splunk
from .sigma import Rule


def _anchor(rule: Rule) -> str:
    return rule.path.stem.replace("_", "-")


def rules_md(rules: list[Rule]) -> str:
    out = ["# Detection rules", "", "Generated from `rules/` by `socdet docs`. Do not edit by hand.", ""]
    out += ["| Rule | Level | Log source | ATT&CK |", "|---|---|---|---|"]
    for r in rules:
        techs = ", ".join(r.techniques)
        out.append(f"| [{r.title}](#{_anchor(r)}) | {r.level} | {r.product}/{r.service} | {techs} |")
    for r in rules:
        out += [
            "",
            f'<a id="{_anchor(r)}"></a>',
            "",
            f"## {r.title}",
            "",
            f"`{r.path.as_posix()}` · level **{r.level}** · id `{r.id}`",
            "",
            r.description,
            "",
            "**ATT&CK:** " + ", ".join(f"[{t}]({technique_url(t)}) {TECHNIQUES.get(t, '')}" for t in r.techniques),
            "",
            "**False positives:** " + "; ".join(r.falsepositives or ["none known"]),
            "",
            "**Splunk (SPL)**",
            "",
            "```spl",
            to_splunk(r),
            "```",
            "",
            "**Microsoft Sentinel (KQL)**",
            "",
            "```kql",
            to_sentinel(r),
            "```",
        ]
    return "\n".join(out) + "\n"


def coverage_md(rules: list[Rule]) -> str:
    cov = coverage(rules)
    out = ["# MITRE ATT&CK coverage", "", "Generated by `socdet docs`.", ""]
    covered = [name for key, name in TACTICS if cov.get(key)]
    out.append(f"{len(rules)} rules cover {len({t for r in rules for t in r.techniques})} techniques "
               f"across {len(covered)} of {len(TACTICS)} tactics.")  # fmt: skip
    out += ["", "| Tactic | Technique | Rules |", "|---|---|---|"]
    for key, name in TACTICS:
        techs = cov.get(key, {})
        if not techs:
            out.append(f"| {name} | *no coverage yet* | |")
            continue
        for tech, tech_rules in sorted(techs.items()):
            links = ", ".join(f"[{r.title}](rules.md#{_anchor(r)})" for r in tech_rules)
            out.append(f"| {name} | [{tech}]({technique_url(tech)}) {TECHNIQUES.get(tech, '')} | {links} |")
    out += [
        "",
        "Gaps are listed on purpose: they show where to write the next rules (for example Discovery and",
        "Lateral Movement, which need endpoint telemetry such as Sysmon or EDR process and network events).",
    ]
    return "\n".join(out) + "\n"
